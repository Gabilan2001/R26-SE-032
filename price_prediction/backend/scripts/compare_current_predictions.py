"""
Compare Current 14-Day Recursive Forecasts (2026-08-29 to 2026-09-11)
generated by Old Production Models vs Retrained Experimental Models across all 4 series.
"""

from pathlib import Path
import pickle
import numpy as np
import pandas as pd
import tensorflow as tf
from tensorflow.keras.models import load_model

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_PATH = BASE_DIR / "datasets" / "tomato_prices_vegetablesSriLanka.csv"
BACKUP_DIR = BASE_DIR / "ml_models" / "backups" / "backup_20260829_101550"
EXP_DIR = BASE_DIR / "ml_models" / "experimental"

SERIES_LIST = [
    ("Dambulla", "Retail"),
    ("Dambulla", "Wholesale"),
    ("Pettah", "Retail"),
    ("Pettah", "Wholesale"),
]

LOOKBACK = 10
MAX_HORIZON = 14

def get_forecast(model, scaler, last_10_prices):
    curr_window_scaled = scaler.transform(np.array(last_10_prices).reshape(-1, 1)).reshape(1, LOOKBACK, 1)
    preds = []
    for _ in range(MAX_HORIZON):
        p_scaled = model.predict(curr_window_scaled, verbose=0)
        p_real = float(scaler.inverse_transform(p_scaled)[0, 0])
        preds.append(p_real)
        curr_window_scaled = np.concatenate([curr_window_scaled[:, 1:, :], p_scaled[:, np.newaxis, :]], axis=1)
    return preds

def main():
    df = pd.read_csv(DATA_PATH)
    df.columns = [c.strip() for c in df.columns]
    df["Date"] = pd.to_datetime(df["Date"])

    print("==================================================================================")
    print(" CURRENT 14-DAY FORECAST COMPARISON (2026-08-29 to 2026-09-11)")
    print("==================================================================================\n")

    forecast_rows = []

    for m, t in SERIES_LIST:
        file_suffix = f"{m.lower()}_{t.lower()}"
        series_label = f"{m}-{t}"

        sub = df[(df["Market"] == m) & (df["Type"] == t)].sort_values("Date").reset_index(drop=True)
        sub["Price"] = pd.to_numeric(sub["Price"], errors="coerce").interpolate(method="linear", limit_direction="both")
        
        last_10 = sub["Price"].values[-LOOKBACK:]
        last_date = sub["Date"].iloc[-1].strftime("%Y-%m-%d")
        ref_p0 = sub["Price"].values[-1]

        old_m = load_model(BACKUP_DIR / f"lstm_{file_suffix}.h5", compile=False)
        with open(BACKUP_DIR / f"scaler_{file_suffix}.pkl", "rb") as f:
            old_s = pickle.load(f)

        new_m = load_model(EXP_DIR / f"lstm_{file_suffix}.h5", compile=False)
        with open(EXP_DIR / f"scaler_{file_suffix}.pkl", "rb") as f:
            new_s = pickle.load(f)

        old_fc = get_forecast(old_m, old_s, last_10)
        new_fc = get_forecast(new_m, new_s, last_10)

        print(f"--- Market Series: {series_label} (Reference P(t) on {last_date} = {ref_p0:.2f} LKR/kg) ---")
        print(f"{'Day':<6} | {'Date':<12} | {'Old Model Forecast':<20} | {'Retrained Forecast':<20} | {'Difference (LKR)':<18}")
        print("-" * 84)

        dates_14 = pd.date_range(start="2026-08-29", periods=14, freq="D")
        for day_idx in range(14):
            d_str = dates_14[day_idx].strftime("%Y-%m-%d")
            old_p = old_fc[day_idx]
            new_p = new_fc[day_idx]
            diff = new_p - old_p
            print(f"Day {day_idx+1:<2} | {d_str:<12} | {old_p:18.2f} | {new_p:18.2f} | {diff:+16.2f}")
            forecast_rows.append({
                "Series": series_label,
                "Day": day_idx + 1,
                "Date": d_str,
                "Old_Forecast_LKR": old_p,
                "Retrained_Forecast_LKR": new_p,
                "Diff_LKR": diff
            })
        print()

    fc_df = pd.DataFrame(forecast_rows)
    fc_df.to_csv(BASE_DIR / "ml_models" / "experimental_14day_forecast_comparison.csv", index=False)
    print("Forecast comparison saved to ml_models/experimental_14day_forecast_comparison.csv")

if __name__ == "__main__":
    main()
